"""Build the zero-backend GitHub Pages site into ./docs.

    python tools/build_pages.py

1. Generates static/catalog.js from iamsentinel/catalog.py (the browser engine's knowledge base,
   so the Python and JavaScript engines share one source of truth).
2. Copies the dashboard (index.html, app.css, app.js, analyzer.js, catalog.js, vendor/) into docs/,
   rewriting absolute /static/ asset URLs to relative ./ URLs so the site works under any
   sub-path such as https://<user>.github.io/IAM-Sentinel/.
3. Pre-computes the full analysis (findings, graph, blast radius, remediation diffs) for
   iam-small.json and samples/iam-multihop-demo.json into docs/data/default-scan.json.
"""
from __future__ import annotations

import dataclasses
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from iamsentinel import __version__, catalog  # noqa: E402
from iamsentinel.engine import analyze  # noqa: E402
from iamsentinel.loader import load_json  # noqa: E402
from iamsentinel.remediation import STAR_ONLY  # noqa: E402

STATIC = ROOT / "static"
DOCS = ROOT / "docs"
SAMPLES = {"default": ROOT / "iam-small.json", "multihop": ROOT / "samples" / "iam-multihop-demo.json"}
COPY = ["app.css", "app.js", "analyzer.js", "catalog.js"]


def catalog_payload() -> dict:
    return {
        "VERSION": __version__,
        "CATEGORIES": catalog.CATEGORIES,
        "SENSITIVE_ACTIONS": catalog.SENSITIVE_ACTIONS,
        "CRITICAL_SERVICES": sorted(catalog.CRITICAL_SERVICES),
        "HIGH_RISK_SERVICES": sorted(catalog.HIGH_RISK_SERVICES),
        "ESCALATION_METHODS": [dataclasses.asdict(m) for m in catalog.ESCALATION_METHODS],
        "BROAD_MANAGED_POLICIES": {k: list(v) for k, v in catalog.BROAD_MANAGED_POLICIES.items()},
        "KNOWN_MANAGED_DOCUMENTS": catalog.KNOWN_MANAGED_DOCUMENTS,
        "STRONG_CONDITION_KEYS": sorted(catalog.STRONG_CONDITION_KEYS),
        "CONFUSED_DEPUTY_SAFE_SERVICES": sorted(catalog.CONFUSED_DEPUTY_SAFE_SERVICES),
        "OIDC_SUBJECT_KEYS": {k: list(v) for k, v in catalog.OIDC_SUBJECT_KEYS.items()},
        "RESOURCE_TEMPLATES": catalog.RESOURCE_TEMPLATES,
        "SERVICE_WORKLOAD_ACTIONS": catalog.SERVICE_WORKLOAD_ACTIONS,
        "ADMIN_PROTECTION_DENY": catalog.ADMIN_PROTECTION_DENY,
        "SERVICE_PRINCIPAL_FOR_ACTION_PREFIX": catalog.SERVICE_PRINCIPAL_FOR_ACTION_PREFIX,
        "MITRE_NAMES": catalog.MITRE_NAMES,
        "STAR_ONLY": sorted(STAR_ONLY),
    }


def write_catalog_js() -> Path:
    out = STATIC / "catalog.js"
    body = json.dumps(catalog_payload(), indent=1, ensure_ascii=False)
    out.write_text("/* GENERATED by tools/build_pages.py from iamsentinel/catalog.py - do not edit by hand. */\n"
                   f"(typeof globalThis !== 'undefined' ? globalThis : window).IAMS_CATALOG = {body};\n", encoding="utf-8")
    return out


def static_index_html() -> str:
    html = (STATIC / "index.html").read_text(encoding="utf-8")
    html = html.replace('"/static/', '"./')
    # tell app.js not to probe for an API server on a static host
    html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="iam-sentinel-mode" content="static">', 1)
    if '"/static/' in html or "'/static/" in html:
        raise SystemExit("index.html still references /static/ after rewrite")
    return html


def build(now: datetime | None = None) -> dict:
    now = now or datetime.now(timezone.utc)
    write_catalog_js()
    # overwrite in place (no rmtree: synced folders such as OneDrive lock directories during deletes)
    DOCS.mkdir(exist_ok=True)
    (DOCS / "index.html").write_text(static_index_html(), encoding="utf-8")
    for name in COPY:
        shutil.copy2(STATIC / name, DOCS / name)
    shutil.copytree(STATIC / "vendor", DOCS / "vendor", dirs_exist_ok=True)
    (DOCS / ".nojekyll").write_text("", encoding="utf-8")

    scans = {}
    for sid, path in SAMPLES.items():
        scans[sid] = analyze(load_json(path), source=path.name, now=now)
    bundle = {"tool": "IAM Sentinel", "version": __version__, "engine": "python", "generated_at": now.isoformat(),
              "default_sample": "default", "samples": scans}
    (DOCS / "data").mkdir(exist_ok=True)
    (DOCS / "data" / "default-scan.json").write_text(json.dumps(bundle, default=str, separators=(",", ":")), encoding="utf-8")
    return bundle


if __name__ == "__main__":
    b = build()
    size = (DOCS / "data" / "default-scan.json").stat().st_size
    for sid, r in b["samples"].items():
        s = r["summary"]
        print(f"{sid:9} {r['meta']['source']:28} grade {s['grade']} ({s['score']}) · {s['findings_total']} findings · "
              f"{s['attack_paths']} paths · {len(r['remediations'])} remediations")
    print(f"docs/ built · data/default-scan.json {size / 1024:.0f} KB")
