#!/usr/bin/env python3
"""IAM Sentinel command line.

    python cli.py scan iam-small.json                       # pretty console summary
    python cli.py scan iam-small.json --fail-on HIGH        # CI gate: exit 1 if any HIGH+ finding
    python cli.py scan export.json --format sarif -o out.sarif
    python cli.py scan export.json --format html -o report.html --write-remediations remediation/
    python cli.py serve [--file export.json] [--port 8000]  # web dashboard
    python cli.py collect --profile audit -o export.json    # live read-only AWS collection (boto3)

Exit codes: 0 = pass, 1 = findings at/above --fail-on threshold, 2 = input/usage error.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

from iamsentinel import __version__
from iamsentinel.engine import analyze
from iamsentinel.loader import IAMParseError, load_json
from iamsentinel.models import SEVERITIES, SEVERITY_RANK
from iamsentinel.reports import EXPORTERS

DEFAULT_FILE = Path(__file__).resolve().parent / "iam-small.json"
COLORS = {"CRITICAL": "\033[1;97;41m", "HIGH": "\033[1;31m", "MEDIUM": "\033[33m", "LOW": "\033[36m", "INFO": "\033[90m"}
RESET = "\033[0m"


def _c(sev: str, text: str, use: bool) -> str:
    return f"{COLORS[sev]}{text}{RESET}" if use else text


def print_table(result: dict, color: bool) -> None:
    s, m = result["summary"], result["meta"]
    print(f"\nIAM Sentinel {m['version']} - account {m['account_id']} ({m['source']})")
    print("=" * 78)
    print(f"Security grade : {s['grade']}  ({s['score']}/100)")
    print(f"Identities     : {s['total_identities']} ({s['users']} users, {s['groups']} groups, {s['roles']} roles)")
    print(f"Attack paths   : {s['attack_paths']} ({s['critical_attack_paths']} critical, {s['multi_hop_paths']} multi-hop)")
    print(f"Excess ratio   : {s['excess_permission_ratio']:.0%} - {s['excess_detail']}")
    print("Findings       : " + "  ".join(_c(k, f"{k}:{v}", color) for k, v in s["findings_by_severity"].items()))
    print("-" * 78)
    for f in result["findings"]:
        who = ", ".join(f["identity_names"][:3])
        pol = f" [{f['policy_name']}{'/' + f['sid'] if f.get('sid') else ''}]" if f.get("policy_name") else ""
        sev = _c(f["severity"], f["severity"].ljust(8), color)
        print(f"{f['id']} {sev} {f['rule_id']:<10} {f['title'][:70]}")
        print(f"{'':13}{who}{pol}")
    print("-" * 78)
    print("Blast radius   : " + ", ".join(f"{i['name']}={i['blast']['score']}" for i in result["identities"] if i["kind"] != "group"))
    if result["remediations"]:
        print(f"Remediations   : {len(result['remediations'])} least-privilege policies generated "
              f"(use --write-remediations DIR to save them with AWS CLI apply scripts)")
    for w in result["meta"]["warnings"]:
        print(f"warning: {w}")


def write_remediations(result: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    script = ["#!/usr/bin/env bash", "# Generated by IAM Sentinel - review every placeholder <LIKE_THIS> before running!", "set -euo pipefail",
              f'cd "$(dirname "$0")/.."',
              f'if grep -lE "<[A-Z0-9_-]+>" {out_dir.as_posix()}/*.json; then',
              '  echo "Refusing to apply: fill in the <PLACEHOLDERS> in the files listed above first." >&2; exit 1',
              "fi", ""]
    for r in result["remediations"]:
        p = out_dir / Path(r["file_name"]).name
        p.write_text(json.dumps(r["proposed"], indent=2), encoding="utf-8")
        script.append(f"# {r['id']} - {r['policy_name']} ({r['max_severity']}) -> {', '.join(r['applies_to'])}")
        if r["placeholders"]:
            script.append(f"# placeholders: {', '.join(r['placeholders'])}")
        script += [c.replace("file://remediation/", f"file://{out_dir.as_posix()}/") for c in r["cli"]] + [""]
    (out_dir / "apply.sh").write_text("\n".join(script), encoding="utf-8")
    print(f"wrote {len(result['remediations'])} policies + apply.sh to {out_dir}", file=sys.stderr)


def cmd_scan(a: argparse.Namespace) -> int:
    try:
        result = analyze(load_json(a.file), source=Path(a.file).name, stale_days=a.stale_days)
    except IAMParseError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    fmt = a.format
    if fmt == "table":
        print_table(result, color=not a.no_color and sys.stdout.isatty() or a.color)
    else:
        text = EXPORTERS[fmt][0](result)
        if a.output:
            Path(a.output).write_text(text, encoding="utf-8")
            print(f"wrote {fmt} report to {a.output}", file=sys.stderr)
        else:
            sys.stdout.reconfigure(encoding="utf-8")
            print(text)
    for extra in a.also or []:
        fmt2, _, path = extra.partition("=")
        if fmt2 in EXPORTERS and path:
            Path(path).write_text(EXPORTERS[fmt2][0](result), encoding="utf-8")
            print(f"wrote {fmt2} report to {path}", file=sys.stderr)
    if a.write_remediations:
        write_remediations(result, Path(a.write_remediations))
    if a.fail_on:
        threshold = SEVERITY_RANK[a.fail_on]
        hits = [f for f in result["findings"] if SEVERITY_RANK[f["severity"]] >= threshold]
        if hits:
            print(f"FAIL: {len(hits)} finding(s) at or above {a.fail_on} (grade {result['summary']['grade']})", file=sys.stderr)
            return 1
        print(f"PASS: no findings at or above {a.fail_on}", file=sys.stderr)
    return 0


def cmd_serve(a: argparse.Namespace) -> int:
    import uvicorn
    if a.file:
        os.environ["IAM_SENTINEL_FILE"] = str(Path(a.file).resolve())
    print(f"IAM Sentinel dashboard -> http://{a.host}:{a.port}  (dataset: {a.file or DEFAULT_FILE.name})")
    uvicorn.run("iamsentinel.server:app", host=a.host, port=a.port, log_level="warning")
    return 0


def cmd_collect(a: argparse.Namespace) -> int:
    from iamsentinel.collector import collect
    try:
        data = collect(profile=a.profile, region=a.region, include_credential_report=not a.no_credential_report,
                       log=lambda m: print(m, file=sys.stderr))
    except Exception as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    Path(a.output).write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"wrote {a.output}; next: python cli.py scan {a.output}", file=sys.stderr)
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="iam-sentinel", description="Cloud Identity & Excessive IAM Permission Detection (PS-07)")
    p.add_argument("--version", action="version", version=f"IAM Sentinel {__version__}")
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan", help="analyse an IAM JSON export")
    s.add_argument("file", nargs="?", default=str(DEFAULT_FILE))
    s.add_argument("--format", "-f", choices=["table"] + list(EXPORTERS), default="table")
    s.add_argument("--output", "-o")
    s.add_argument("--also", action="append", metavar="FMT=PATH", help="write additional reports, e.g. --also sarif=out.sarif")
    s.add_argument("--fail-on", choices=SEVERITIES, type=str.upper, help="exit 1 if any finding has this severity or higher")
    s.add_argument("--stale-days", type=int, default=90)
    s.add_argument("--write-remediations", metavar="DIR", help="write least-privilege policies + apply.sh")
    s.add_argument("--no-color", action="store_true")
    s.add_argument("--color", action="store_true")
    s.set_defaults(fn=cmd_scan)
    v = sub.add_parser("serve", help="start the web dashboard")
    v.add_argument("--file")
    v.add_argument("--host", default="127.0.0.1")
    v.add_argument("--port", type=int, default=8000)
    v.set_defaults(fn=cmd_serve)
    c = sub.add_parser("collect", help="collect a live IAM snapshot (read-only, boto3)")
    c.add_argument("--profile")
    c.add_argument("--region")
    c.add_argument("--output", "-o", default="iam-live-export.json")
    c.add_argument("--no-credential-report", action="store_true")
    c.set_defaults(fn=cmd_collect)
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
